; XYBOTS - MSX1 + V9990 B1 ROM (Phase 5). Derived from MSX/src/rom/xybots_rom.asm (same boot: RAM search, copy engine); adds the
; V9990 presence check before anything else and the V9990 boot hook. Assemble with SJASM via V9990-P1/tools/build_b1.py.
;
; The tape original is a BIOS-less program that lives in RAM at 0300h-FFFEh (see MSX/doc/memory-map.md,
; ADR-002): it needs RAM in all four pages, so this ROM is only a data source during boot:
;
;   1. The BIOS calls INIT (below) with page 1 = this cartridge, interrupts disabled.
;   2. Stage A (this file, bank 0) checks for the V9990 (message and stop if absent), finds the RAM slot (page 3), copies
;      the small stage B into unused RAM (C200h, inside the never-accessed zone C125h-EAFFh) and jumps to it.
;   3. Stage B (stage_b_b1.asm) copies the game image piece by piece: ASCII16 bank -> 4 KiB buffer DA00h (ROM visible
;      in page 1), then all pages to RAM, buffer -> original address. The pieces include the V9990 hook runtime
;      (C400h-D5FFh). Nothing of the ROM is needed afterwards.
;      Before stage B runs, the opening picture (opening.asm, ADR-023) is shown until fire is pressed.
;   4. Stage B calls the hook boot (V9990 init, palette, planes, display on), then `JP 0300h` starts the game.
;
; ROM layout (ASCII16, 16 KiB banks, register 6000h selects the bank of 4000h-7FFFh):
;   bank 0, offset 0000h: header, stage A, stage B image, chunk table; data pieces follow from offset 0400h.
;   rom_data.inc (generated by MSX/tools/build_rom.py) lists the pieces; a piece never crosses a bank boundary.
; Slots (ADR-053): page 1 of the cartridge slot is the only cartridge window of the game (INIT leaves its sub-slot selected, so a
; cartridge in an expanded slot works: user, real MSX, 2026-10-16); the voice upload of the OPL4 player opens page 2 as well and sets
; the sub-slot itself (ms_vsel). RAM is searched in the primary slots at 8000h; when the RAM slot is expanded, its sub-slot register is
; set so that all four pages hold the RAM (the BIOS maps only pages 2-3: Philips NMS 8250). RAM and cartridge in the same expanded slot
; is refused with a message. Machines with less than 64 KiB RAM cannot run the game.

        include "../defs.asm"
ROM_A           equ 0xc1f0      ; slot register value with page 1 = cartridge, other pages RAM (set by stage A)
RAM_A           equ 0xc1f1      ; slot register value with all four pages = RAM slot
BOOT            equ 0xc200      ; stage B run address (page 3 RAM, unused area of the original image)
OPENING         equ 0xc500      ; opening picture routine (src/rom/opening.asm), runs once before stage B
CHPUT           equ 0x00a2      ; BIOS: print character in A (page 0 is still the BIOS at this point)

        org 0x4000
        db "AB"                 ; cartridge ID
        dw rom_init             ; INIT
        dw 0                    ; STATEMENT
        dw 0                    ; DEVICE
        dw 0                    ; TEXT
        ds 6,0

; rom_init - entered by the BIOS, page 1 = this cartridge. Never returns.
; In:  interrupts disabled. The BIOS may have page 3 in a slot that only mirrors the RAM (Sony HB-10P: slot 0),
;      so the RAM slot is found by a write test in page 2 instead of being assumed.
rom_init:
        di
        ld a,(0x002d)                   ; MSX version id: 3 = turbo R. The game and the port are timed for the Z80 (V9990 and OPL4 port
        cp 3                            ; accesses, line-interrupt waits): CHGCPU to Z80 mode, LED off (ADR-052; the BIOS is in page 0)
        jr c,.z80
        ld a,0x80                       ; bit 7: update the LED; mode 0 = Z80
        call 0x0180                     ; CHGCPU
        di                              ; (CHGCPU may return with interrupts enabled)
.z80:   call v9_detect_a
        jr z,v9_present
        ld hl,msg_no_v9990              ; the BIOS is still mapped in page 0: print and stop
msg_halt:
        ld a,(hl)
        and a
        jr z,halt_loop
        push hl
        call CHPUT
        pop hl
        inc hl
        jr msg_halt
halt_loop:
        di
        jr halt_loop
same_slot:
        ld a,e
        out (0xa8),a                    ; the BIOS layout again (page 0 = BIOS for CHPUT, page 3 = its stack)
        ld hl,msg_same_slot
        jr msg_halt
v9_present:
        in a,(0xa8)
        ld e,a                  ; E = primary slot register set by the BIOS (page 1 = this cartridge)
        ld b,0                  ; B = candidate primary slot
find_ram:
        ld a,b
        add a,a
        add a,a
        add a,a
        add a,a                 ; candidate slot in the page 2 bits (4-5)
        ld c,a
        ld a,e
        and 0xcf
        or c
        out (0xa8),a            ; page 2 = candidate slot, page 1 stays the cartridge
        ld a,(0x8000)
        cpl
        ld l,a
        ld (0x8000),a
        ld a,(0x8000)
        cp l
        jr z,ram_slot_found     ; the complemented value was stored: RAM (ROM, mirrors and empty slots fail)
        inc b
        ld a,b
        cp 4
        jr nz,find_ram
; No primary slot has RAM at 8000h: the RAM is in an expanded slot. Assume it is the slot of page 3.
        ld a,e
        rlca
        rlca
        and 3
        ld b,a
        ld d,1                  ; D = 1: sub-slot handling needed below
        jr ram_slot_set
ram_slot_found:
        ld d,0
ram_slot_set:
        ld a,b                  ; A = RAM slot
        add a,a
        add a,a
        or b
        ld c,a                  ; C = slot | slot<<2
        rlca
        rlca
        rlca
        rlca
        or c
        ld c,a                  ; C = RAM slot in all four pages
        ld a,e
        and 0x0c                ; slot selected in page 1 = this cartridge (bits 2-3)
        ld b,a
        ld a,c
        and 0xf3
        or b
        ld b,a                  ; B = RAM everywhere except page 1 = cartridge
        ld a,b
        ld (ROM_A),a
        ld a,c
        ld (RAM_A),a
        ld a,b
        out (0xa8),a            ; pages 0, 2, 3 = the RAM slot, page 1 = this cartridge. From here to the sub-slot write below
                                ; nothing uses the stack or page 3 (an expanded RAM slot may not have RAM there yet)
; Expanded RAM slot (ADR-053): FFFFh is its sub-slot register (reads back complemented). The BIOS calls INIT with its RAM in pages 2-3
; only: on a Philips NMS 8250 (RAM in 3-2) pages 0-1 of slot 3 are on the sub ROM, so the game image copied there was lost. All four
; pages get the sub-slot of the page where RAM was found (page 2; page 3 when no primary slot had RAM: D = 1).
        ld a,(0xffff)
        cpl
        ld h,a                  ; H = current sub-slot register (or a RAM byte)
        ld (0xffff),a
        ld a,(0xffff)
        cp h
        jr z,ram_not_expanded   ; plain RAM
        ld a,b
        and 0x0c
        rrca
        rrca
        ld l,a                  ; L = slot of this cartridge
        ld a,c
        and 3
        cp l
        jr z,same_slot          ; the RAM and the cartridge share the expanded slot: page 1 cannot be switched by the primary register
        ld a,d
        or a
        ld a,h
        jr z,.p2
        rrca
        rrca                    ; page 3 bits down to the page 2 position
.p2:    and 0x30
        rrca
        rrca
        rrca
        rrca                    ; A = sub-slot of the RAM (0..3)
        ld l,a
        add a,a
        add a,a
        or l
        ld l,a
        rlca
        rlca
        rlca
        rlca
        or l
        ld (0xffff),a           ; same sub-slot in all four pages
ram_not_expanded:
        ld hl,stage_b_rom
        ld de,BOOT
        ld bc,stage_b_end-stage_b_rom
        ldir
        ld hl,opening_rom               ; the opening picture runs first (from RAM: it switches the ROM bank window) and ends in BOOT
        ld de,OPENING
        ld bc,opening_end_rom-opening_rom
        ldir
        jp OPENING

; v9_detect_a - reset the V9990, write 5Ah,A5h at VRAM 0 and read them back. Out: Z = present.   Clobbers: AF
v9_detect_a:
        ld a,2
        out (V9_SYSCTRL),a              ; SRS = 1
        xor a
        out (V9_SYSCTRL),a              ; release reset
        out (V9_REGSEL),a               ; R#0
        out (V9_REGDATA),a              ; write address 0 (R#0-R#2)
        out (V9_REGDATA),a
        out (V9_REGDATA),a
        ld a,0x5a
        out (V9_VRAM),a
        ld a,0xa5
        out (V9_VRAM),a
        ld a,3
        out (V9_REGSEL),a               ; R#3
        xor a
        out (V9_REGDATA),a              ; read address 0 (R#3-R#5)
        out (V9_REGDATA),a
        out (V9_REGDATA),a
        in a,(V9_VRAM)
        cp 0x5a
        ret nz
        in a,(V9_VRAM)
        cp 0xa5
        ret

msg_no_v9990:
        db 13,10,"This cartridge needs a V9990.",13,10,0
msg_same_slot:
        db 13,10,"The RAM and this cartridge share an expanded slot:",13,10,"put the cartridge in another slot.",13,10,0

stage_b_rom:
        incbin "../../build/rom/stage_b.bin"
stage_b_end:
opening_rom:
        incbin "../../build/rom/opening.bin"
opening_end_rom:
        assert $ <= 0x4800      ; the data pieces start at ROM offset 0800h in the V9990 build
        include "../../build/rom/rom_data.inc"
