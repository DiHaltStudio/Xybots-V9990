def regions(ins, note):
    """The regions (layers) of instrument ins (0-127 GM program, 128 drum kit) that play MIDI note note."""
    return [r for r in REGIONS[INS_START[ins]:INS_START[ins + 1]] if r[0] <= note <= r[1]]


def find(name):
    """GM instrument number by (part of) its name."""
    low = name.lower()
    for k, n in enumerate(NAMES):
        if low in n.lower():
            return k
    raise KeyError(name)
